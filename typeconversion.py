#int to other types
a=20
print(type(a))
print(str(a))           #int to string
print(float(a))         #int to float
print(bool(a))          #int to boolean
print(complex(a))       #int to complex

#float to other types
b=23.8
print(type(b))
print(str(b))          #float to string
print(int(b))          #float to int
print(bool(b))         #float to boolean
print(complex(b))      #float to complex

#string to other types
s="68"
print(type(s))
print(int(s))          #string to int
print(float(s))        #string to float
print(bool(s))         #string to boolean
print(complex(s))      #string to complex

#boolean to other types
x=True
print(type(x))    
print(str(x))         #boolean to string
print(int(x))         #boolean to int
print(float(x))       #boolean to float
print(complex(x))     #boolean to complex

#complex to other types
u=6+4j
print(type(u))
print(str(u))          #complex to string
print(bool(u))         #complex to boolean
  
